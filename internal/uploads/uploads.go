// Package uploads owns the on-disk layout of admin-uploaded files:
// content-addressed naming, writing, safe removal, content sniffing and
// serving. Handlers hand it bytes and get back public URL paths.
package uploads

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// URLPrefix is the public path prefix of every uploaded file.
const URLPrefix = "/uploads/"

// generatedName matches names produced by Save:
// <prefix>-<sha256 prefix>.<ext>. Only matching files are ever deleted,
// so /static/ seed files and hand-placed files are never touched.
var generatedName = regexp.MustCompile(`^[a-z][a-z-]*-[0-9a-f]{16}\.(pdf|jpg|jpeg|png|webp)$`)

// Store is a directory of uploaded files.
type Store struct {
	dir string
}

// NewStore creates a store rooted at dir. The directory is created
// lazily on the first Save.
func NewStore(dir string) *Store {
	return &Store{dir: dir}
}

// Save writes data as <prefix>-<content hash><ext> and returns its public
// URL path. The name is content-addressed: identical bytes under the same
// prefix map to the same URL, and any change yields a fresh URL.
func (s *Store) Save(prefix string, data []byte, ext string) (string, error) {
	sum := sha256.Sum256(data)
	name := prefix + "-" + hex.EncodeToString(sum[:])[:16] + ext

	if err := os.MkdirAll(s.dir, 0o755); err != nil {
		return "", err
	}

	if err := os.WriteFile(filepath.Join(s.dir, name), data, 0o644); err != nil {
		return "", err
	}

	return URLPrefix + name, nil
}

// Remove deletes the file behind urlPath, keeping the one at keepPath.
// It is best effort and only ever removes files generated by Save inside
// the store directory; other paths (including /static/ seeds) are ignored.
func (s *Store) Remove(urlPath, keepPath string) {
	if urlPath == "" || urlPath == keepPath {
		return
	}

	if name, ok := s.name(urlPath); ok {
		_ = os.Remove(filepath.Join(s.dir, name))
	}
}

// Exists reports whether the file behind a generated upload URL exists.
func (s *Store) Exists(urlPath string) bool {
	name, ok := s.name(urlPath)
	if !ok {
		return false
	}

	info, err := os.Stat(filepath.Join(s.dir, name))

	return err == nil && !info.IsDir()
}

// Handler serves stored files (mount it with URLPrefix stripped) with a
// long immutable cache lifetime: names embed a content hash, so a changed
// file is always a new URL.
func (s *Store) Handler() http.Handler {
	fs := http.FileServer(http.Dir(s.dir))

	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Cache-Control", "public, max-age=31536000, immutable")
		w.Header().Set("X-Content-Type-Options", "nosniff")
		// PDFs are served as downloads to avoid inline polyglot XSS.
		if strings.HasSuffix(strings.ToLower(r.URL.Path), ".pdf") {
			w.Header().Set("Content-Disposition", "attachment")
			w.Header().Set("X-Download-Options", "noopen")
		}
		fs.ServeHTTP(w, r)
	})
}

// name extracts the file name from a generated upload URL.
func (s *Store) name(urlPath string) (string, bool) {
	name := strings.TrimPrefix(urlPath, URLPrefix)
	if name == urlPath || strings.Contains(name, "/") || !generatedName.MatchString(name) {
		return "", false
	}

	return name, true
}

// DetectImage checks data is a non-empty JPEG, PNG or WebP of at most
// maxBytes and returns the file extension for storage.
func DetectImage(data []byte, maxBytes int) (string, bool) {
	if len(data) == 0 || len(data) > maxBytes {
		return "", false
	}

	switch http.DetectContentType(data) {
	case "image/jpeg":
		return ".jpg", true
	case "image/png":
		return ".png", true
	case "image/webp":
		return ".webp", true
	default:
		return "", false
	}
}

// ReadFormFile reads a single multipart file field, capped at limit+1
// bytes so oversize uploads are detected. It returns an error when the
// field is missing or empty.
func ReadFormFile(r *http.Request, field string, limit int64) ([]byte, error) {
	file, _, err := r.FormFile(field)
	if err != nil {
		return nil, err
	}

	defer file.Close()

	data, err := io.ReadAll(io.LimitReader(file, limit+1))
	if err != nil || len(data) == 0 {
		return nil, errors.New("empty upload")
	}

	return data, nil
}
